/**
 * Writes the SQL that loads `localities` (the centre of every ABS suburb) and `postcodes` (the
 * centre of every ABS postal area) for "near me" search, into a custom migration:
 *
 *   bun db:generate -- --custom --name <name>
 *   bun tools/directory/localities.ts packages/db/migrations/<that file>.sql
 *
 * Run once per ASGS edition (the 2021 edition is in 0002_location_data.sql). Suburb slugs come
 * from the app's own `slugify`, so they match the `suburb_slug` of salons and jobs.
 */
import { slugify } from "../../packages/shared/src/urls";
import { suburbName } from "./src/clean";
import { duckdb, quote, requireDuckdb } from "./src/duckdb";
import { absBoundaries } from "./src/sources";

const out = process.argv[2];
if (!out?.endsWith(".sql")) {
  console.error("Usage: bun tools/directory/localities.ts packages/db/migrations/<migration>.sql");
  process.exit(1);
}
requireDuckdb();

const STATES: Record<string, string> = {
  "New South Wales": "NSW",
  Victoria: "VIC",
  Queensland: "QLD",
  "Western Australia": "WA",
  "South Australia": "SA",
  Tasmania: "TAS",
  "Australian Capital Territory": "ACT",
  "Northern Territory": "NT",
};

const boundaries = await absBoundaries();
console.log("• Finding the centre of every suburb and postcode (about a minute)…");
const suburbs = await duckdb<{
  code: string;
  name: string;
  state: string;
  postcodes: string[];
  latitude: number;
  longitude: number;
}>(`
  INSTALL spatial;
  LOAD spatial;
  CREATE TEMP TABLE suburbs AS
    SELECT SAL_CODE21 AS code, SAL_NAME21 AS name, STE_NAME21 AS state, geom
    FROM ST_Read(${quote(boundaries.suburbs)})
    WHERE geom IS NOT NULL AND NOT regexp_matches(SAL_NAME21, 'Remainder|No usual address|Migratory|Offshore');
  CREATE TEMP TABLE areas AS
    SELECT POA_CODE21 AS postcode, geom FROM ST_Read(${quote(boundaries.postcodes)})
    WHERE geom IS NOT NULL AND regexp_matches(POA_CODE21, '^\\d{4}$');
  -- The postal areas a suburb lies in: any holding at least 1% of it, largest share first.
  CREATE TEMP TABLE shares AS
    SELECT s.code, a.postcode, ST_Area(ST_Intersection(s.geom, a.geom)) / ST_Area(s.geom) AS share
    FROM suburbs s JOIN areas a ON ST_Intersects(s.geom, a.geom);
  SELECT s.code, s.name, s.state,
         list(o.postcode ORDER BY o.share DESC) FILTER (WHERE o.share >= 0.01) AS postcodes,
         round(ST_Y(ST_Centroid(s.geom)), 5) AS latitude,
         round(ST_X(ST_Centroid(s.geom)), 5) AS longitude
  FROM suburbs s LEFT JOIN shares o ON o.code = s.code
  GROUP BY s.code, s.name, s.state, s.geom
  ORDER BY s.code;
`);
const postcodes = await duckdb<{ postcode: string; latitude: number; longitude: number }>(`
  INSTALL spatial;
  LOAD spatial;
  SELECT POA_CODE21 AS postcode,
         round(ST_Y(ST_Centroid(geom)), 5) AS latitude,
         round(ST_X(ST_Centroid(geom)), 5) AS longitude
  FROM ST_Read(${quote(boundaries.postcodes)})
  WHERE geom IS NOT NULL AND regexp_matches(POA_CODE21, '^\\d{4}$')
  ORDER BY postcode;
`);

const text = (v: string) => quote(v);
const array = (vs: string[]) => `ARRAY[${vs.map(text).join(",")}]::text[]`;
const localityRows = suburbs
  .filter((s) => STATES[s.state])
  .map((s) => {
    const suburb = suburbName(s.name);
    return `(${[
      text(s.code),
      text(STATES[s.state] as string),
      text(suburb),
      text(slugify(suburb)),
      array(s.postcodes ?? []),
      s.latitude,
      s.longitude,
    ].join(",")})`;
  });
const postcodeRows = postcodes.map((p) => `(${text(p.postcode)},${p.latitude},${p.longitude})`);

// One INSERT per 1,000 rows, each its own migration statement.
const inserts = (head: string, rows: string[]) =>
  Array.from(
    { length: Math.ceil(rows.length / 1000) },
    (_, i) => `${head}\n${rows.slice(i * 1000, (i + 1) * 1000).join(",\n")};`,
  );
const header =
  "-- Generated by tools/directory/localities.ts from the ABS Suburbs and Localities and Postal Areas,\n-- ASGS Edition 3 (2021), CC BY 4.0. Don't edit by hand.\n";
const sql = [
  ...inserts(
    'INSERT INTO "localities" ("code","state","suburb","suburb_slug","postcodes","latitude","longitude") VALUES',
    localityRows,
  ),
  ...inserts('INSERT INTO "postcodes" ("postcode","latitude","longitude") VALUES', postcodeRows),
].join("\n--> statement-breakpoint\n");
await Bun.write(out, `${header}${sql}\n`);
console.log(
  `  ${localityRows.length.toLocaleString("en-AU")} suburbs and ${postcodeRows.length.toLocaleString("en-AU")} postcodes → ${out}`,
);
